for (const [relative, url, expectedMd5] of assets) {
  const response = await fetch(url, { redirect: 'follow' });
  if (!response.ok) throw new Error(`Asset download failed (${response.status}): ${relative}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  const actualMd5 = createHash('md5').update(bytes).digest('hex');
  if (actualMd5 !== expectedMd5) throw new Error(`Asset checksum mismatch: ${relative}`);
  const path = resolve(root, relative);
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, bytes);
  console.log(`${relative}: ${bytes.length} bytes, MD5 verified`);
}

